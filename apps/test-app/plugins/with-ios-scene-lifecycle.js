const { withAppDelegate, withInfoPlist } = require('expo/config-plugins');

const GENERATED_MARKER = '// @generated by with-ios-scene-lifecycle';

const LEGACY_WINDOW_SETUP = `#if os(iOS) || os(tvOS)
    window = UIWindow(frame: UIScreen.main.bounds)
    factory.startReactNative(
      withModuleName: "main",
      in: window,
      launchOptions: launchOptions)
#endif`;

const TV_WINDOW_SETUP = `#if os(tvOS)
    window = UIWindow(frame: UIScreen.main.bounds)
    factory.startReactNative(
      withModuleName: "main",
      in: window,
      launchOptions: launchOptions)
#endif`;

const SCENE_CONFIGURATION = `${GENERATED_MARKER}
#if os(iOS)
  public func application(
    _ application: UIApplication,
    configurationForConnecting connectingSceneSession: UISceneSession,
    options: UIScene.ConnectionOptions
  ) -> UISceneConfiguration {
    return UISceneConfiguration(
      name: "Default Configuration",
      sessionRole: connectingSceneSession.role)
  }
#endif

`;

const SCENE_DELEGATE = `${GENERATED_MARKER}
#if os(iOS)
final class SceneDelegate: UIResponder, UIWindowSceneDelegate {
  var window: UIWindow?

  func scene(
    _ scene: UIScene,
    willConnectTo session: UISceneSession,
    options connectionOptions: UIScene.ConnectionOptions
  ) {
    guard
      let windowScene = scene as? UIWindowScene,
      let appDelegate = UIApplication.shared.delegate as? AppDelegate,
      let factory = appDelegate.reactNativeFactory
    else {
      return
    }

    let window = UIWindow(windowScene: windowScene)
    self.window = window
    appDelegate.window = window
    factory.startReactNative(
      withModuleName: "main",
      in: window,
      launchOptions: nil)
  }
}
#endif

`;

function addSceneLifecycleToAppDelegate(contents) {
  if (contents.includes(GENERATED_MARKER)) {
    return contents;
  }

  if (!contents.includes(LEGACY_WINDOW_SETUP)) {
    throw new Error(
      'Could not find the Expo iOS window setup in AppDelegate.swift. Update with-ios-scene-lifecycle.js for the installed Expo template.',
    );
  }

  const linkingMarker = '  // Linking API\n';
  const reactNativeDelegateMarker = 'class ReactNativeDelegate: ExpoReactNativeFactoryDelegate {';
  if (!contents.includes(linkingMarker) || !contents.includes(reactNativeDelegateMarker)) {
    throw new Error(
      'Could not find the expected insertion points in AppDelegate.swift. Update with-ios-scene-lifecycle.js for the installed Expo template.',
    );
  }

  return contents
    .replace(LEGACY_WINDOW_SETUP, TV_WINDOW_SETUP)
    .replace(linkingMarker, SCENE_CONFIGURATION + linkingMarker)
    .replace(reactNativeDelegateMarker, SCENE_DELEGATE + reactNativeDelegateMarker);
}

module.exports = function withIosSceneLifecycle(config) {
  config = withInfoPlist(config, (config) => {
    config.modResults.UIApplicationSceneManifest = {
      UIApplicationSupportsMultipleScenes: false,
      UISceneConfigurations: {
        UIWindowSceneSessionRoleApplication: [
          {
            UISceneConfigurationName: 'Default Configuration',
            UISceneDelegateClassName: '$(PRODUCT_MODULE_NAME).SceneDelegate',
          },
        ],
      },
    };
    return config;
  });

  return withAppDelegate(config, (config) => {
    if (config.modResults.language !== 'swift') {
      throw new Error('with-ios-scene-lifecycle only supports a Swift AppDelegate.');
    }
    config.modResults.contents = addSceneLifecycleToAppDelegate(config.modResults.contents);
    return config;
  });
};
